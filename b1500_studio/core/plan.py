"""Waveform plan model (10 ns tick grid) and SI parsing helpers.

Faithful port of ``pkg/src/plan.h``.  Qt-free, instrument-free, numpy-free:
this module is pure logic so it can be unit-tested without hardware.

All times are carried as integer *ticks* of :data:`GRID` (10 ns), exactly as
the C++ model does, so that a plan built in Python lands on the same WGFMU
sample boundaries as the one built by the Qt app.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import List, Sequence, Tuple

__all__ = [
    "GRID",
    "PlanError",
    "ticks",
    "secs",
    "parse_si",
    "parse_list",
    "Vec",
    "Event",
    "Plan",
    "Wave",
]

GRID = 10e-9  # WGFMU time resolution (10 ns)


class PlanError(ValueError):
    """Invalid waveform, timing or parameter text."""


def ticks(s: float) -> int:
    """Seconds -> integer ticks on the 10 ns grid. Raises below one tick."""
    n = int(round(s / GRID))
    if n < 1:
        raise PlanError("time below the 10 ns WGFMU grid")
    return n


def secs(n: int) -> float:
    """Integer ticks -> seconds."""
    return float(n) * GRID


# --------------------------------------------------------------- SI parsing

_SI_PREFIX = {"p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "M": 1e6}
_ALLOWED_UNITS = {"", "s", "S", "V", "A", "Hz"}
_NUMBER_RE = re.compile(
    r"^\s*([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*(.*)$", re.S
)


def parse_si(text) -> float:
    """``"50n"``, ``"1.5u"``, ``"2m"``, ``"1e-6"``, ``"100 ns"`` -> float.

    Accepts both Unicode micro signs (U+00B5 and U+03BC) as ``u``.
    """
    if isinstance(text, (int, float)):
        return float(text)
    s = str(text).replace("µ", "u").replace("μ", "u").strip()
    if not s:
        raise PlanError("empty number")
    m = _NUMBER_RE.match(s)
    if not m:
        raise PlanError(f"cannot parse '{text}'")
    value = float(m.group(1))
    rest = m.group(2).strip()
    factor = 1.0
    if rest:
        if rest[0] in _SI_PREFIX:
            factor = _SI_PREFIX[rest[0]]
            rest = rest[1:]
        if rest not in _ALLOWED_UNITS:
            raise PlanError(f"cannot parse '{text}'")
    return value * factor


def parse_list(text) -> List[float]:
    """``"1u,10u"`` | ``"log(50n,100u,5)"`` | ``"lin(0.5,1,6)"`` -> list."""
    s = str(text).strip()
    low = s.lower()
    if (low.startswith("log(") or low.startswith("lin(")) and low.endswith(")"):
        logarithmic = low[2] == "g"
        parts = s[4:-1].split(",")
        if len(parts) != 3:
            raise PlanError("use log(start,stop,n) or lin(start,stop,n)")
        a, b = parse_si(parts[0]), parse_si(parts[1])
        n = int(parse_si(parts[2]))
        if n < 1:
            raise PlanError("n must be >= 1")
        if logarithmic and (a <= 0 or b <= 0):
            raise PlanError("log list needs positive limits")
        out: List[float] = []
        for i in range(n):
            f = 0.0 if n == 1 else i / (n - 1)
            out.append(a * (b / a) ** f if logarithmic else a + (b - a) * f)
        return out

    cleaned = s.replace(";", " ").replace("\t", " ")
    out = []
    for token in cleaned.split(","):
        for word in token.split():
            out.append(parse_si(word))
    if not out:
        raise PlanError("empty list")
    return out


# ------------------------------------------------------------- plan objects


@dataclass
class Vec:
    """One piecewise-linear segment: ramp to ``v`` over ``n`` ticks."""

    n: int
    v: float


@dataclass
class Event:
    """One measurement event, all times in ticks."""

    name: str
    t: int
    points: int
    interval: int
    avg: int


@dataclass
class Plan:
    """One force pattern plus its measure events.

    The sink pattern is generated by the driver, matching the C++ design.
    """

    vec: List[Vec] = field(default_factory=list)
    ev: List[Event] = field(default_factory=list)
    hint: str = ""  # "synapse" | "neuron" -- only the demo simulator uses it

    def total(self) -> int:
        """Total pattern length in ticks."""
        return sum(x.n for x in self.vec)

    def duration(self) -> float:
        """Total pattern length in seconds."""
        return secs(self.total())

    def n_points(self) -> int:
        """Total number of measurement samples."""
        return sum(e.points for e in self.ev)

    def max_abs_v(self) -> float:
        """Largest |V| anywhere in the pattern."""
        return max((abs(x.v) for x in self.vec), default=0.0)

    def voltage_at(self, tick: float) -> float:
        """Drive voltage at ``tick``, interpolated along the piecewise ramps.

        The sample list carries times but not the level they were taken at,
        and for a swept protocol -- a P-V triangle, a C-V staircase -- the
        level is the independent variable of the whole measurement. Without
        this, analysis would have to re-derive the waveform it just built.
        """
        if not self.vec:
            return 0.0
        edge_t = 0.0
        level = 0.0
        for seg in self.vec:
            end = edge_t + float(seg.n)
            if tick <= end:
                span = max(end - edge_t, 1e-12)
                f = min(max((tick - edge_t) / span, 0.0), 1.0)
                return level + (seg.v - level) * f
            edge_t = end
            level = seg.v
        return level

    def sample_voltages(self) -> List[float]:
        """Drive voltage at every sample centre, in device order."""
        out: List[float] = []
        for e in self.ev:
            for k in range(e.points):
                out.append(self.voltage_at(e.t + k * e.interval + e.avg / 2.0))
        return out

    def samples(self) -> Tuple[List[float], List[int]]:
        """Centre time (s) and event index of every sample, in device order."""
        t: List[float] = []
        ev_idx: List[int] = []
        for i, e in enumerate(self.ev):
            for k in range(e.points):
                t.append((e.t + k * e.interval + e.avg / 2.0) * GRID)
                ev_idx.append(i)
        return t, ev_idx

    def validate(self, vmax: float, max_points: int) -> None:
        """Raise :class:`PlanError` unless the plan is safe and well formed."""
        if not self.vec:
            raise PlanError("empty waveform")
        if self.max_abs_v() > vmax + 1e-12:
            raise PlanError(
                f"|V| = {self.max_abs_v():g} V exceeds the safety limit "
                f"{vmax:g} V (Instrument tab)"
            )
        tot = self.total()
        prev_end = 0
        for e in self.ev:
            if e.points < 1 or e.interval < 1 or e.avg < 1 or e.avg > e.interval:
                raise PlanError(
                    f"event '{e.name}': bad points/interval/averaging"
                )
            end = e.t + (e.points - 1) * e.interval + e.avg
            if e.t < prev_end:
                raise PlanError(f"event '{e.name}' overlaps the previous one")
            if end > tot:
                raise PlanError(
                    f"event '{e.name}' runs past the end of the pattern"
                )
            prev_end = end
        if self.n_points() > max_points:
            raise PlanError(
                f"{self.n_points()} data points exceed the limit {max_points}"
            )


class Wave:
    """Piecewise-linear voltage builder that appends into a :class:`Plan`."""

    def __init__(self, plan: Plan) -> None:
        self._plan = plan
        self._n = 0
        self._v = 0.0

    def to(self, v: float, n: int) -> int:
        """Ramp to ``v`` over ``n`` ticks; returns the new cursor in ticks."""
        self._plan.vec.append(Vec(int(n), float(v)))
        self._n += int(n)
        self._v = float(v)
        return self._n

    def hold(self, n: int) -> int:
        """Hold the present level for ``n`` ticks."""
        return self.to(self._v, n)

    def now(self) -> int:
        """Current cursor position in ticks."""
        return self._n

    @property
    def v(self) -> float:
        """Current voltage level."""
        return self._v
